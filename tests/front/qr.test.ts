const toMatrix = (rows: string[]): QrMatrix => rows.map((r) => [...r].map((ch) => ch === '#'));

afterEach(() => {
  vi.doUnmock('qrcode-generator');
  vi.resetModules();
});

describe('qrMatrix', () => {
  for (const [text, rows] of Object.entries(STORED)) {
    it(`equals the stored matrix for ${JSON.stringify(text)}`, () => {
      expect(qrMatrix(text)).toEqual(toMatrix(rows));
    });
  }

  it('returns null when the library throws', async () => {
    vi.resetModules();
    vi.doMock('qrcode-generator', () => ({
      default: () => {
        throw new Error('forced failure');
      },
    }));
    const mod = await import('../../src/front/qr');
    expect(mod.qrMatrix('https://deadair.vedasdixit.com/listen/')).toBeNull();
  });
});

describe('qrSvgShape', () => {
  for (const [text, rows] of Object.entries(STORED)) {
    it(`has size matrix + 8 and a clear margin for ${JSON.stringify(text)}`, () => {
      const m = toMatrix(rows);
      const { size, d } = qrSvgShape(m);
      expect(QUIET_MODULES).toBe(4);
      expect(size).toBe(m.length + 8);
      const cells = [...d.matchAll(/M(\d+) (\d+)h1v1h-1z/g)].map((x) => [Number(x[1]), Number(x[2])]);
      const dark = rows.join('').split('#').length - 1;
      expect(cells).toHaveLength(dark);
      for (const [x, y] of cells) {
        expect(x).toBeGreaterThanOrEqual(4);
        expect(y).toBeGreaterThanOrEqual(4);
        expect(x + 1).toBeLessThanOrEqual(size - 4);
        expect(y + 1).toBeLessThanOrEqual(size - 4);
      }
    });
  }
});
