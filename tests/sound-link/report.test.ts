// Runs the measurements and writes .kiro/specs/sound-link/report.md from the numbers. All in memory.
import { describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import type { SoundMode } from '../../src/sound-link';
import { buildStream, classify, listenTo, makeLink, makeRawGgwave, makeRng, randomPayload, sendOnce } from './harness';
import type { Outcome } from './harness';

const MODES: SoundMode[] = ['AUDIBLE_NORMAL', 'AUDIBLE_FAST', 'AUDIBLE_FASTEST'];
const LEVELS: (number | null)[] = [null, 20, 10, 0, -10, -15, -20, -25, -30]; // null means no noise
const SIZES = [21, 40];
const PER_CELL = 20;
const OFFSETS = [0, 100, 333, 512, 777, 1000, 1023];

interface Counts { exact: number; nothing: number; wrong: number }
const empty = (): Counts => ({ exact: 0, nothing: 0, wrong: 0 });
const bump = (c: Counts, o: Outcome) => void (c[o] += 1);
const cell = (c: Counts) => `${c.exact} / ${c.nothing} / ${c.wrong}`;
const label = (db: number | null) => (db === null ? 'no noise' : `${db} dB`);

describe('measurements and report', () => {
  it('measures airtime and noise, writes report.md, and checks the shares', async () => {
    const lines: string[] = [];
    const out = (s = '') => lines.push(s);

    // 1. Airtime at 48000 Hz.
    const raw = await makeRawGgwave();
    const links = new Map<SoundMode, Awaited<ReturnType<typeof makeLink>>>();
    for (const m of MODES) links.set(m, await makeLink({ mode: m }));
    const airtime = new Map<string, number>();
    for (const m of MODES) {
      airtime.set(`${m}:19`, raw.encode(new Uint8Array(19).fill(7), m).length / 48000);
      for (const n of [21, 40]) {
        const a = links.get(m)!.bytesToAudio(new Uint8Array(n).fill(7));
        if (!a.ok) throw new Error(a.reason);
        airtime.set(`${m}:${n}`, a.samples.length / 48000);
      }
    }

    // 2. Noise sweep.
    const sweep = new Map<string, Counts>();
    for (const m of MODES) {
      for (const db of LEVELS) {
        for (const n of SIZES) {
          const counts = empty();
          const rng = makeRng(1000 + n + (db ?? 99) * 7 + MODES.indexOf(m) * 100003);
          for (let i = 0; i < PER_CELL; i++) {
            const bytes = randomPayload(rng, n);
            const r = sendOnce(links.get(m)!, bytes, {
              leadSamples: Math.floor(rng() * 1024),
              snrDb: db ?? undefined,
              rng,
              tailSeconds: 2,
            });
            bump(counts, r.outcome);
          }
          sweep.set(`${m}:${label(db)}:${n}`, counts);
        }
      }
    }

    // 3. Short payloads, straight through ggwave, FAST mode, no noise.
    const shortCounts = new Map<string, Counts>();
    {
      const rng = makeRng(31337);
      const fast = links.get('AUDIBLE_FAST')!;
      for (let n = 1; n <= 20; n++) {
        const group = n <= 7 ? '1 to 7' : n <= 14 ? '8 to 14' : '15 to 20';
        const counts = shortCounts.get(group) ?? empty();
        for (let i = 0; i < 5; i++) {
          const bytes = randomPayload(rng, n);
          const stream = buildStream(raw.encode(bytes, 'AUDIBLE_FAST'), { sampleRate: 48000 });
          bump(counts, classify(bytes, listenTo(fast, stream, 1024)));
        }
        shortCounts.set(group, counts);
      }
    }

    // 4. Does sending again help? Same payload at seven start offsets, FAST mode, no noise.
    let retryTotal = 0;
    let retryAlways = 0;
    let retrySometimesMissed = 0;
    let retryRecovered = 0;
    let retryWrong = 0;
    {
      const rng = makeRng(4242);
      const fast = links.get('AUDIBLE_FAST')!;
      for (let i = 0; i < 60; i++) {
        const bytes = randomPayload(rng, 21 + Math.floor(rng() * 20));
        const results = OFFSETS.map((lead) => sendOnce(fast, bytes, { leadSamples: lead }).outcome);
        retryTotal++;
        if (results.every((r) => r === 'exact')) retryAlways++;
        else {
          retrySometimesMissed++;
          if (results.includes('exact')) retryRecovered++;
        }
        retryWrong += results.filter((r) => r === 'wrong').length;
      }
    }

    // Write the report.
    out('# Sound Link report');
    out();
    out('Generated by `tests/sound-link/report.test.ts` from in-memory runs. Do not edit by hand.');
    out(`ggwave 0.4.0, 48000 Hz, volume 10. Each noise cell is ${PER_CELL} seeded random payloads sent once. White Gaussian noise is added to the whole stream, including the silence around the sound. The level is the ratio of the sound's power to the noise power over the whole band up to 24 kHz. ggwave's tones sit in a small part of that band, so it still decodes at ratios below 0 dB.`);
    out();
    out('## Airtime');
    out();
    out('| Payload | NORMAL | FAST | FASTEST |');
    out('|---|---|---|---|');
    for (const n of [19, 21, 40]) {
      out(`| ${n} bytes${n === 19 ? ' (ggwave directly)' : ''} | ${MODES.map((m) => airtime.get(`${m}:${n}`)!.toFixed(2) + ' s').join(' | ')} |`);
    }
    out();
    out('## Noise');
    out();
    out('Each cell shows how many of the payloads were heard `exact / nothing / wrong`. A `wrong` result is bytes that differ from what was sent. Only the Message Code check stops those.');
    for (const m of MODES) {
      out();
      out(`### ${m}`);
      out();
      out(`| Signal to noise | 21 bytes | 40 bytes |`);
      out('|---|---|---|');
      for (const db of LEVELS) out(`| ${label(db)} | ${SIZES.map((n) => cell(sweep.get(`${m}:${label(db)}:${n}`)!)).join(' | ')} |`);
    }
    out();
    out('## Payloads shorter than 21 bytes');
    out();
    out('Sent through ggwave directly in FAST mode with no noise, 5 seeded payloads per length. The Sound Link Encoder refuses these sizes. The Listener reports whatever it hears.');
    out();
    out('| Length | exact / nothing / wrong |');
    out('|---|---|');
    for (const [g, c] of shortCounts) out(`| ${g} bytes | ${cell(c)} |`);
    out();
    out('## Does sending again help?');
    out();
    out(`${retryTotal} seeded payloads of 21 to 40 bytes, each sent at ${OFFSETS.length} different start offsets inside the first frame, FAST mode, no noise.`);
    out();
    out(`- Exact at every offset: ${retryAlways}`);
    out(`- Missed or wrong at some offset: ${retrySometimesMissed}`);
    out(`- Of those, heard exactly at another offset: ${retryRecovered}`);
    out(`- Results with wrong bytes, over all ${retryTotal * OFFSETS.length} sends: ${retryWrong}`);
    out();
    out('## What a real room still has to show');
    out();
    out('White noise is not a room. Echo, a phone speaker and a phone microphone change the sound in ways this test does not. A test with real speakers and phones is still needed (sound rules). Results go into the Field tests table in `docs/kiro-diary.md`.');
    writeFileSync('.kiro/specs/sound-link/report.md', lines.join('\n') + '\n');

    for (const l of links.values()) l.dispose();
    raw.free();

    // Assertions. Wrong bytes are counted and reported but not asserted away under noise.
    const fastClean = (n: number) => sweep.get(`AUDIBLE_FAST:no noise:${n}`)!;
    const fast20 = (n: number) => sweep.get(`AUDIBLE_FAST:20 dB:${n}`)!;
    for (const n of SIZES) {
      expect(fastClean(n).wrong, `FAST no noise ${n} bytes`).toBe(0);
      expect(fastClean(n).exact / PER_CELL, `FAST no noise ${n} bytes`).toBeGreaterThanOrEqual(0.9);
      expect(fast20(n).exact / PER_CELL, `FAST 20 dB ${n} bytes`).toBeGreaterThanOrEqual(0.8);
    }
    expect(retryWrong).toBe(0);
  }, 600_000);
});
